#!/usr/bin/env python
"""
make_synthetic_notes.py — regenerate experiments/synthetic_multiloop/index.md.

Why this exists separately from experiments/make_notes.py:

  1. make_notes.py discovers notes.json only ONE level below experiments/, so
     anything under synthetic_multiloop/runN/ is invisible to it (which is why
     run 800 never appeared in the main index).
  2. It parses finetune_deterministic.py's stdout, which the synthetic scripts
     do not emit.
  3. Its 21-field schema is built around session/fusion/soft-threshold, none of
     which apply to a synthetic loop run.

Rather than bend either, this family keeps its own index. A pointer line in the
main experiments/index.md keeps the primary log from being silently incomplete.

Usage:
    python experiments/synthetic_multiloop/make_synthetic_notes.py
"""
from __future__ import annotations

import json
import pathlib
from datetime import datetime

HERE = pathlib.Path(__file__).resolve().parent


def load_runs():
    """Read every runN/ directory that carries a result file."""
    runs = []
    for d in sorted(HERE.iterdir()):
        if not d.is_dir() or not d.name.startswith("run"):
            continue
        record = {"dir": d.name, "run": int(d.name[3:]) if d.name[3:].isdigit()
                  else None}

        notes = d / "notes.json"
        evalf = d / "per_loop_eval.json"
        onlin = d / "online_summary.json"

        if notes.exists():
            record["notes"] = json.loads(notes.read_text())
        if evalf.exists():
            record["eval"] = json.loads(evalf.read_text())
        if onlin.exists():
            record["online"] = json.loads(onlin.read_text())["summary"]
        if len(record) > 2:
            runs.append(record)
    runs.sort(key=lambda r: (r["run"] is None, r["run"]))
    return runs


def _ppo_row(r):
    e = r.get("eval") or {}
    n = r.get("notes") or {}
    agg = e.get("aggregate", {})
    acc = agg.get("mean_accuracy", n.get("best_acc"))
    sen = agg.get("mean_sensors", n.get("sensors_at_best"))
    return (
        f"| {r['run']} | {e.get('time_limit', n.get('time_limit', '—'))} "
        f"| {e.get('max_sensors', n.get('max_sensors', '—'))} "
        f"| {e.get('sensor_rew', n.get('sensor_rew', '—'))} "
        f"| {'—' if acc is None else f'{acc*100:.2f}%'} "
        f"| {'—' if sen is None else f'{sen:.2f}'} "
        f"| {agg.get('std_accuracy', 0)*100:.2f}pp "
        f"| {e.get('best_iteration', n.get('best_iteration', '—'))} "
        f"| {e.get('converged', n.get('converged', '—'))} |"
    )


def _online_row(r):
    o = r["online"]
    lat = o.get("mean_latency_episodes")
    det = o.get("detector") or {}
    return (
        f"| {r['run']} | {o.get('max_sensors')} | {o.get('restart_strategy')} "
        f"| {'yes' if o.get('detector_enabled') else 'no'} "
        f"| {o.get('mean_accuracy', 0)*100:.2f}% "
        f"| {o.get('mean_sensors', 0):.2f} "
        f"| {'—' if lat is None else f'{lat:.1f}'} "
        f"| {o.get('n_restarts', '—')} "
        f"| {det.get('true_positive', '—')}/{det.get('n_switches', '—')} "
        f"| {det.get('false_alarms', '—')} |"
    )


def main():
    runs = load_runs()
    ppo    = [r for r in runs if "eval" in r or "notes" in r]
    online = [r for r in runs if "online" in r]

    out = [
        "# Synthetic multi-loop experiments",
        "",
        f"_Auto-generated by `make_synthetic_notes.py` — "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')}._",
        "",
        "Runs where the object walks generated loops over the Camp Buckner",
        "topology, with no audio, camera or GPS in the path. Separate from the",
        "main `experiments/index.md`, which covers the live-data PPO runs; see",
        "the module docstring of `make_synthetic_notes.py` for why.",
        "",
        "**Ceiling:** `evaluate_policy` starts every episode in the missing",
        "state and counts that step in the denominator but never the numerator,",
        "so the maximum achievable accuracy is `(max_ep_steps-1)/max_ep_steps`",
        "= **99.00%** at the default 100 steps. Treat 99.00% as perfect.",
        "",
    ]

    if ppo:
        out += [
            "## Batch runs (PPO)",
            "",
            "| Run | tl | max_sens | sensor_rew | Mean acc | Sensors/step "
            "| sd | Best iter | Converged |",
            "|-----|----|----------|------------|----------|--------------"
            "|----|-----------|-----------|",
        ]
        out += [_ppo_row(r) for r in ppo]
        out.append("")

    if online:
        out += [
            "## Online runs (tabular TD on a sequential loop schedule)",
            "",
            "| Run | max_sens | Restart | Detector | Mean acc | Sensors/step "
            "| Latency (ep) | Restarts | Switches caught | False alarms |",
            "|-----|----------|---------|----------|----------|--------------"
            "|--------------|----------|-----------------|--------------|",
        ]
        out += [_online_row(r) for r in online]
        out.append("")

    out += ["## Per-run detail", ""]
    for r in runs:
        n = r.get("notes") or {}
        out.append(f"### {r['dir']}")
        if n.get("hypothesis"):
            out += ["", f"**Hypothesis:** {n['hypothesis']}"]
        if n.get("findings"):
            out += ["", f"**Findings:** {n['findings']}"]
        files = sorted(p.name for p in (HERE / r["dir"]).iterdir())
        out += ["", f"**Files:** {', '.join(files)}", ""]

    (HERE / "index.md").write_text("\n".join(out) + "\n")
    print(f"Wrote {HERE / 'index.md'} ({len(runs)} runs: "
          f"{len(ppo)} batch, {len(online)} online)")


if __name__ == "__main__":
    main()
